# 宏观→板块映射（与config.py MACRO_SECTOR_ROTATION同步）
MACRO_TO_SECTORS = {
    "复苏期": ["消费", "金融", "汽车", "地产基建"],
    "扩张期": ["科技", "半导体", "AI算力", "新能源", "军工"],
    "过热期": ["能源", "金融"],
    "衰退期": ["医药", "消费"],
    "default": ["科技", "消费", "医药"],
}

def get_stocks_for_macro(regime: str) -> List[str]:
    """根据宏观状态返回推荐扫描的股票列表 — 保持稳定顺序"""
    sector_names = MACRO_TO_SECTORS.get(regime, MACRO_TO_SECTORS["default"])
    _seen_m = set()
    _result = []
    for name in sector_names:
        for s in LDS_SECTORS.get(name, []):
            if s not in _seen_m:
                _seen_m.add(s)
                _result.append(s)
    return _result


